class _SimFeeder(QtCore.QObject):
    """
    Lightweight data simulator for testing the LiveGraphWindow standalone.
    Periodically appends rows into the provided list[dict].
    """
    def __init__(self, data_ref: List[Dict[str, Any]], kind: str = "power", period_ms: int = 200, parent=None):
        super().__init__(parent)
        self.data_ref = data_ref
        self.kind = kind
        self.t = 0
        self.timer = QtCore.QTimer(self)
        self.timer.timeout.connect(self._tick)
        self.timer.start(period_ms)
        random.seed(108)

        # baselines
        self.v = 15.9  # 4S LiPo pack-ish under light load
        self.i_esp = 0.09
        self.i_pi = 0.55
        self.i_fc = 0.10
        self.i_modem = 0.05

        self.temp = 16.0
        self.ph = 7.6
        self.turb = 5.0
        self.no3 = 0.25
        self.po4 = 0.02

    def _now_iso(self):
        return datetime.datetime.now(datetime.UTC).strftime("%H:%M:%S")


    def _tick(self):
        self.t += 1
        if self.kind == "power":
            # Wiggle currents with some cycles
            self.i_esp  = max(0.05, 0.09 + 0.02 * math.sin(self.t/20.0) + random.uniform(-0.005, 0.005))
            self.i_pi   = max(0.35, 0.55 + 0.10 * math.sin(self.t/30.0) + random.uniform(-0.02, 0.02))
            self.i_fc   = max(0.05, 0.10 + 0.03 * math.sin(self.t/25.0) + random.uniform(-0.01, 0.01))
            self.i_modem= max(0.03, 0.05 + 0.03 * (math.sin(self.t/12.0) > 0) + random.uniform(-0.01, 0.01))
            total_i = self.i_esp + self.i_pi + self.i_fc + self.i_modem

            # Simulate slow voltage sag + tiny ripple
            self.v -= total_i * 0.0005  # very gentle decline
            self.v += 0.01 * math.sin(self.t/15.0)
            self.v = max(12.8, min(16.8, self.v))

            self.data_ref.append({
                "timestamp": self._now_iso(),
                "v_batt": round(self.v, 3),
                "i_esp": round(self.i_esp, 3),
                "i_pi": round(self.i_pi, 3),
                "i_fc": round(self.i_fc, 3),
                "i_modem": round(self.i_modem, 3),
            })
        else:
            # Sensor drift + noise
            self.temp += random.uniform(-0.02, 0.02)
            self.ph   += random.uniform(-0.005, 0.005)
            self.turb += random.uniform(-0.1, 0.1)
            self.no3  += random.uniform(-0.002, 0.002)
            self.po4  += random.uniform(-0.0005, 0.0005)

            self.temp = max(5.0, min(30.0, self.temp))
            self.ph   = max(6.5, min(8.5, self.ph))
            self.turb = max(0.0, min(100.0, self.turb))
            self.no3  = max(0.0, self.no3)
            self.po4  = max(0.0, self.po4)

            self.data_ref.append({
                "timestamp": self._now_iso(),
                "temperature": round(self.temp, 2),
                "ph": round(self.ph, 2),
                "turbidity": round(self.turb, 2),
                "nitrate": round(self.no3, 3),
                "phosphate": round(self.po4, 3),
            })


