import math
from typing import List, Dict, Any, Optional, Sequence
from PyQt5 import QtWidgets, QtCore
import pyqtgraph as pg
import sys
import random
import datetime

PALETTE = [
    "#1f77b4", "#ff7f0e", "#2ca02c", "#d62728", "#9467bd",
    "#8c564b", "#e377c2", "#7f7f7f", "#bcbd22", "#17becf",
]


class LiveGraphWindow(QtWidgets.QDialog):
    """
    GENERATED BY CHATGPT
    Generic, non-blocking live graph window for a list[dict] data source.

    Args:
        data_ref: list of dicts you append to (e.g., GUI.power_data / GUI.sensor_data).
        panels: [
          {"title": "...", "series": [{"key":"field_in_row","name":"Legend Name"}, ...]},
          ...
        ]
        x_mode: "index" (simple) or "timestamp" (expects 'timestamp' string key; uses index here for speed)
        max_points: keep only last N samples in the plotted view for performance
        update_ms: refresh period in milliseconds
    """ 
    def __init__(
        self,
        data_ref: List[Dict[str, Any]],
        panels: Sequence[Dict[str, Any]],
        x_mode: str = "index",
        max_points: Optional[int] = 1000,
        update_ms: int = 300,
        parent=None,
    ):
        super().__init__(parent)
        self.setWindowTitle("Live Graph")
        self.resize(1000, 600)

        self.data_ref = data_ref
        self.panels_cfg = list(panels)
        self.x_mode = x_mode
        self.max_points = max_points

        pg.setConfigOptions(
            background="w",   # white plot background
            foreground="k",   # black axes/labels/legend text & pens
            antialias=True
        )

        self._plots: List[pg.PlotWidget] = []
        self._curves: List[List[pg.PlotDataItem]] = []

        layout = QtWidgets.QVBoxLayout(self)

        for panel in self.panels_cfg:
            plot = pg.PlotWidget(
                title=panel.get("title", ""),
                axisItems={"bottom": pg.DateAxisItem(orientation="bottom")}
            )
            plot.showGrid(x=True, y=True, alpha=0.25)  # light grey grid on white
            legend = plot.addLegend()
            # Make legend frame white with black border
            legend.setBrush("w")
            legend.setPen(pg.mkPen("k"))

            # Black axes + tick labels
            for ax in ("left", "bottom"):
                a = plot.getAxis(ax)
                a.setPen(pg.mkPen("k"))
                a.setTextPen(pg.mkPen("k"))

            curves = []
            for idx, s in enumerate(panel.get("series", [])):
                color = PALETTE[idx % len(PALETTE)]
                curve = plot.plot(
                    name=s.get("name", s.get("key", "")),
                    pen=pg.mkPen(color, width=2)   # unique colour per series
                )
                curves.append(curve)

            self._plots.append(plot)
            self._curves.append(curves)
            layout.addWidget(plot)


        self._timer = QtCore.QTimer(self)
        self._timer.timeout.connect(self._refresh)
        self._timer.start(update_ms)

    # ---------- Helpers ----------
    @staticmethod
    def _safe_float(x) -> Optional[float]:
        try:
            return float(x)
        except Exception:
            return None

    @staticmethod
    def _fill_gaps(series: List[Optional[float]], default=0.0) -> List[float]:
        last = default
        out = []
        for v in series:
            if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
                out.append(last)
            else:
                out.append(v)
                last = v
        return out

    # ---------- Core refresh ----------
    def _refresh(self):
        rows = self.data_ref
        if not rows:
            return

        # Efficient tail view
        start_idx = 0
        if self.max_points is not None and len(rows) > self.max_points:
            start_idx = len(rows) - self.max_points
        view = rows[start_idx:]

        # --- X: simple indices (no conversion) ---
        x = list(range(start_idx, start_idx + len(view)))

        # Build labels straight from your JSON timestamps ("HH:mm:ss")
        labels = [str(r.get("timestamp", "")) for r in view]

        # Downsample labels so they don't overlap (aim for ~8 labels)
        if len(labels) > 0:
            step = max(1, len(labels) // 8)
            tick_list = [(start_idx + i, labels[i]) for i in range(0, len(labels), step)]
        else:
            tick_list = []

        # Update each panel
        for plot, curves, panel_cfg in zip(self._plots, self._curves, self.panels_cfg):
            # Set bottom-axis ticks to your timestamp strings
            ax = plot.getAxis("bottom")
            ax.setTicks([tick_list])  # major ticks only, exact labels from JSON

            series_cfg = panel_cfg.get("series", [])
            for curve, s in zip(curves, series_cfg):
                key = s.get("key")
                vals_raw = [self._safe_float(r.get(key)) for r in view]
                vals = self._fill_gaps(vals_raw, default=0.0)
                curve.setData(x, vals)



